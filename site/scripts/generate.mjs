// Generates reference pages from the plugin's own artifacts so the docs cannot drift:
//   ../oclif.manifest.json  → src/pages/reference/commands.mdx
//   ../src/**/*.ts           → src/pages/reference/errors.mdx  (ENSV2_* codes + hints)
//   ../dist/lib/deployments.js → src/pages/reference/deployment.mdx
// Run `npm run build` in the plugin root first. Output is committed.
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const out = join(here, "..", "src", "pages", "reference");
const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/</g, "&lt;").replace(/\{/g, "&#123;").replace(/\}/g, "&#125;");
const banner = (src) => `{/* GENERATED by site/scripts/generate.mjs from ${src} — do not edit by hand. */}\n`;

// ---------- commands
const manifest = JSON.parse(readFileSync(join(root, "oclif.manifest.json"), "utf8"));
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const caps = Object.fromEntries(pkg.mm.commands.map((c) => [c.id, c]));
const hostFlags = new Set(["format", "json", "toon", "verbose", "help"]);
const cmds = Object.values(manifest.commands).sort((a, b) => a.id.localeCompare(b.id));
const topics = {};
for (const c of cmds) {
  const parts = c.id.split(":");
  const topic = parts.length > 2 ? parts.slice(0, 2).join(" ") : parts[0];
  (topics[topic] ??= []).push(c);
}
let md = `---\ntitle: Commands\ndescription: "Every mm ensv2 command, generated from the plugin's oclif manifest (${cmds.length} commands, v${pkg.version})."\n---\n\n` + banner("oclif.manifest.json + package.json#mm") + `\n# Commands\n\n`;
md += `Generated from the plugin's own \`oclif.manifest.json\` at version **${pkg.version}** — ${cmds.length} commands. Every command accepts \`--json\` for machine-readable output and \`--chain <id>\` (default 11155111, Sepolia; anything else is refused).\n\n`;
md += `| Command | Capabilities | What it does |\n|---|---|---|\n`;
for (const c of cmds) {
  const inv = "mm " + c.id.replace(/:/g, " ");
  const cap = (caps[c.id]?.capabilities ?? []).join(", ");
  md += `| [\`${inv}\`](#${inv.replace(/ /g, "-")}) | ${cap} | ${esc(c.description?.split(". ")[0])} |\n`;
}
md += `\n`;
for (const [topic, list] of Object.entries(topics)) {
  md += `## \`mm ${topic}\`\n\n`;
  for (const c of list) {
    const inv = "mm " + c.id.replace(/:/g, " ");
    const meta = caps[c.id] ?? {};
    md += `### \`${inv}\`\n\n${esc(c.description)}\n\n`;
    md += `- **Capabilities:** ${(meta.capabilities ?? []).map((x) => `\`${x}\``).join(", ") || "—"}  \n- **Data access:** ${(meta.dataAccess ?? []).map((x) => `\`${x}\``).join(", ") || "—"}  \n- **Signs a transaction:** ${meta.capabilities?.includes("wallet-submit") ? "yes, through MetaMask policy (MFA)" : "no"}\n\n`;
    const args = Object.values(c.args ?? {});
    if (args.length) {
      md += `**Arguments**\n\n| Name | Required | Description |\n|---|---|---|\n`;
      for (const a of args) md += `| \`${a.name}\` | ${a.required ? "yes" : "no"} | ${esc(a.description)} |\n`;
      md += `\n`;
    }
    const flags = Object.values(c.flags ?? {}).filter((f) => !hostFlags.has(f.name) && !(c.args && c.args[f.name]));
    if (flags.length) {
      md += `**Flags**\n\n| Flag | Description |\n|---|---|\n`;
      for (const f of flags) md += `| \`--${f.name}\` | ${esc(f.description)} |\n`;
      md += `\n`;
    }
    if (c.examples?.length) md += "**Examples**\n\n```sh\n" + c.examples.map((e) => e.replace("<%= config.bin %>", "mm")).join("\n") + "\n```\n\n";
  }
}
writeFileSync(join(out, "commands.mdx"), md);

// ---------- errors: ENSV2_* codes from source, with the message and hint text next to them
const files = [];
(function walk(d) { for (const f of readdirSync(d)) { const p = join(d, f); statSync(p).isDirectory() ? walk(p) : p.endsWith(".ts") && files.push(p); } })(join(root, "src"));
const codes = new Map();
const re = /new (?:CommandError|ReadError)\(\s*"(ENSV2_[A-Z0-9_]+)"\s*,\s*(`[^`]*`|"(?:[^"\\]|\\.)*")\s*(?:,\s*(`[^`]*`|"(?:[^"\\]|\\.)*"))?/gs;
for (const f of files) {
  const src = readFileSync(f, "utf8");
  for (const m of src.matchAll(re)) {
    const clean = (s) => s?.slice(1, -1).replace(/\$\{[^}]*\}/g, "…").replace(/\\"/g, '"').replace(/\s+/g, " ").trim();
    const e = codes.get(m[1]) ?? { code: m[1], where: new Set(), message: clean(m[2]), hint: clean(m[3]) };
    e.where.add(f.replace(root + "/", ""));
    codes.set(m[1], e);
  }
}
let em = `---\ntitle: Error codes\ndescription: "Every ENSV2_* error the plugin can raise, with the hint it prints: the next action for a human or an agent."\n---\n\n` + banner("src (every .ts file)") + `\n# Error codes\n\nEvery failure is a typed \`CommandError\` with a stable code, a message, and a **hint** that names the next action. With \`--json\`, agents read \`error.code\` and \`error.hint\`. Nothing is written on any of these: every write is planned, simulated and verified around the single transaction it sends.\n\n| Code | Message | Hint (what to do) |\n|---|---|---|\n`;
for (const e of [...codes.values()].sort((a, b) => a.code.localeCompare(b.code))) em += `| \`${e.code}\` | ${esc(e.message)} | ${esc(e.hint ?? "")} |\n`;
em += `\nThe durable-jobs engine (\`provision\`, \`jobs\`) additionally reports the program's frozen \`E_*\` codes from \`schemas/errors.schema.json\` (vendored 1.0.0), for example \`E_RECEIPT_UNAVAILABLE\` (a step was submitted and its outcome is unknown — halt, check chain, never resend automatically) and \`E_IDEMPOTENCY_CONFLICT\`.\n`;
writeFileSync(join(out, "errors.mdx"), em);

// ---------- deployment table
const { SEPOLIA } = await import(join(root, "dist", "lib", "deployments.js"));
const labels = {
  universalResolver: "Universal Resolver (proxy) — public entry point; navigation + resolution",
  rootRegistry: "Root registry — top of the v2 hierarchy",
  registry: ".eth registry (PermissionedRegistry) — where 2LDs live",
  registrar: "ETH registrar — commit/reveal registration, ERC-20 payment",
  rentPriceOracle: "Rent price oracle",
  paymentToken: "MockUSDC — the beta's payment token (open faucet)",
  resolverFactory: "VerifiableFactory — deploys and attests per-wallet resolvers",
  resolverImplementation: "PermissionedResolver implementation",
  resolverProxyLogic: "Factory clone target (ERC-1167 proxy logic)",
  subregistryImplementation: "UserRegistry implementation",
  adapter8004: "Adapter8004 proxy (unruggable-labs/adapter) — mints + binds ERC-8004 agents",
  identityRegistry: "ERC-8004 IdentityRegistry (canonical Sepolia)",
  reverseRegistrar: "v1 ReverseRegistrar — owner of addr.reverse (reverse namespace is v1 infra at launch)",
};
let dm = `---\ntitle: Deployment table\ndescription: "The pinned ENSv2 Sepolia beta deployment the plugin talks to, and how each address is re-verified at runtime."\n---\n\n` + banner("dist/lib/deployments.js") + `\n# Deployment table\n\nChain **${SEPOLIA.chainId}** (Sepolia), deployment id \`${SEPOLIA.deploymentId}\`. Mainnet is deliberately absent: ENSv2 is a beta with non-final interfaces, and the plugin refuses any other chain.\n\nThese values are never trusted blindly. \`mm ensv2 status\` re-derives the registry from the Universal Resolver and refuses to run if the table disagrees; the resolver factory's clone target, the adapter's implementation (EIP-1967 slot) and the reverse registrar (root → reverse TLD resolver → v1 registry) are each re-derived on use.\n\n| Contract | Address | Role |\n|---|---|---|\n`;
for (const [k, v] of Object.entries(SEPOLIA)) if (typeof v === "string" && v.startsWith("0x")) dm += `| \`${k}\` | [\`${v}\`](https://sepolia.etherscan.io/address/${v}) | ${labels[k] ?? ""} |\n`;
dm += `\nProvenance: the official table at [docs.ens.domains/learn/deployments](https://docs.ens.domains/learn/deployments/#sepolia-ensv2-beta), the checked-in \`deployments/sepolia/*.json\` artifacts, the official \`ens-cli\` table, and live verification. Note that the ENS contracts repo's \`contracts/src/\` does **not** match the deployed Sepolia contracts; the plugin was built against the deployment artifacts and the ENS docs, never against that source tree.\n`;
writeFileSync(join(out, "deployment.mdx"), dm);
console.log(`generated: ${cmds.length} commands, ${codes.size} error codes, ${Object.keys(SEPOLIA).length} deployment fields`);
